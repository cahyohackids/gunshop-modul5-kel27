-- ---------------------------------------------------------------------------
-- products
-- ---------------------------------------------------------------------------
create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  name        text        not null,
  type        text        not null default 'Pistol',
  caliber     text        default '9mm',
  price       numeric(12,2) not null default 0,
  description text        default '',
  specs       text[]      not null default '{}',
  image_url   text,                                   -- cover photo (= images[1])
  images      text[]      not null default '{}',      -- #9 multiple photos
  seller_wa   text,                                   -- #8 seller WhatsApp (628…)
  deleted_at  timestamptz,                            -- #6 soft delete / archive
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

-- In case the table already existed without the Day 2 columns
alter table public.products add column if not exists images     text[] not null default '{}';
alter table public.products add column if not exists seller_wa  text;
alter table public.products add column if not exists deleted_at timestamptz;

create index if not exists products_deleted_at_idx on public.products (deleted_at);
create index if not exists products_created_at_idx on public.products (created_at desc);

-- ---------------------------------------------------------------------------
-- reviews
-- ---------------------------------------------------------------------------
create table if not exists public.reviews (
  id          bigint generated by default as identity primary key,
  product_id  bigint      not null references public.products (id) on delete cascade,
  user_id     uuid        not null,
  user_name   text,
  rating      smallint    not null check (rating between 1 and 5),
  comment     text        default '',
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);
alter table public.reviews add column if not exists user_name  text;
alter table public.reviews add column if not exists updated_at timestamptz not null default now();
create index if not exists reviews_product_id_idx on public.reviews (product_id);

-- ---------------------------------------------------------------------------
-- review_votes — #7 thumbs up (1) / thumbs down (-1), one vote per user
-- ---------------------------------------------------------------------------
create table if not exists public.review_votes (
  review_id   bigint      not null references public.reviews (id) on delete cascade,
  user_id     uuid        not null,
  vote        smallint    not null check (vote in (-1, 1)),
  created_at  timestamptz not null default now(),
  primary key (review_id, user_id)
);

-- ---------------------------------------------------------------------------
-- favorites
-- ---------------------------------------------------------------------------
create table if not exists public.favorites (
  user_id     uuid        not null,
  product_id  bigint      not null references public.products (id) on delete cascade,
  created_at  timestamptz not null default now(),
  primary key (user_id, product_id)
);
create index if not exists favorites_product_id_idx on public.favorites (product_id);

-- ---------------------------------------------------------------------------
-- Row Level Security
-- The app has no login (anonymous UUID per browser), so the publishable key
-- may read & write these tables. Fine for a praktikum demo — add Supabase
-- Auth + per-user policies before using this for anything real.
-- ---------------------------------------------------------------------------
alter table public.products     enable row level security;
alter table public.reviews      enable row level security;
alter table public.review_votes enable row level security;
alter table public.favorites    enable row level security;

do $$
declare t text;
begin
  foreach t in array array['products', 'reviews', 'review_votes', 'favorites'] loop
    execute format('drop policy if exists "public read" on public.%I', t);
    execute format('drop policy if exists "public insert" on public.%I', t);
    execute format('drop policy if exists "public update" on public.%I', t);
    execute format('drop policy if exists "public delete" on public.%I', t);
    execute format('create policy "public read"   on public.%I for select to anon, authenticated using (true)', t);
    execute format('create policy "public insert" on public.%I for insert to anon, authenticated with check (true)', t);
    execute format('create policy "public update" on public.%I for update to anon, authenticated using (true) with check (true)', t);
    execute format('create policy "public delete" on public.%I for delete to anon, authenticated using (true)', t);
  end loop;
end $$;

